const SCRIPT = `
const quickTab = document.getElementById('tab-quick');
const guideTab = document.getElementById('tab-guide');
const quickView = document.getElementById('view-quick');
const guideView = document.getElementById('view-guide');
const filter = document.getElementById('filter');
const empty = document.getElementById('empty');

function show(which) {
  const quick = which === 'quick';
  quickView.hidden = !quick;
  guideView.hidden = quick;
  quickTab.classList.toggle('active', quick);
  guideTab.classList.toggle('active', !quick);
  quickTab.setAttribute('aria-selected', String(quick));
  guideTab.setAttribute('aria-selected', String(!quick));
  applyFilter();
}

quickTab.addEventListener('click', () => { show('quick'); });
guideTab.addEventListener('click', () => { show('guide'); });

function applyFilter() {
  const needle = filter.value.trim().toLowerCase();
  const view = quickView.hidden ? guideView : quickView;
  let visible = 0;

  for (const row of view.querySelectorAll('tr')) {
    const match = needle === '' || row.textContent.toLowerCase().includes(needle);
    row.hidden = !match;
    if (match) visible += 1;
  }
  for (const card of view.querySelectorAll('.card')) {
    const match = needle === '' || card.dataset.search.includes(needle);
    card.hidden = !match;
    if (match) visible += 1;
  }
  for (const group of view.querySelectorAll('.group')) {
    const rows = [...group.querySelectorAll('tr, .card')];
    group.hidden = rows.length > 0 && rows.every((node) => node.hidden);
  }
  empty.hidden = visible > 0;
}

filter.addEventListener('input', applyFilter);
`;
