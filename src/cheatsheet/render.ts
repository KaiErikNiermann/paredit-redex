/**
 * Renders the cheat sheet to a self-contained HTML document.
 *
 * Pure: no `vscode` import, so the markup is unit-testable. Colours come from
 * the editor's own theme variables rather than a palette of our own, so the page
 * matches whatever theme the reader is using.
 */

import { CARET } from "../ops/caret-notation";
import type { CatalogEntry, EntryGroup } from "./catalog";
import { CATALOG } from "./catalog";
import { exampleFor } from "./examples";

const GROUP_ORDER: readonly EntryGroup[] = ["Navigate", "Depth", "Kill", "Rearrange", "Help"];

const GROUP_BLURB: Readonly<Record<EntryGroup, string>> = {
  Navigate: "Move by structure instead of by character. Nothing here changes the text.",
  Depth: "Change how deeply nested something is — the heart of paredit.",
  Kill: "Delete whole data, so the brackets always stay balanced.",
  Rearrange: "Reorder and regroup siblings within a list.",
  Help: "",
};

export function escapeHtml(text: string): string {
  return text
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

/** Render a caret-marked snippet, showing the caret as a cursor rather than a glyph. */
export function renderSnippet(marked: string): string {
  const [before = "", after = ""] = marked.split(CARET);
  return `${escapeHtml(before)}<span class="caret"></span>${escapeHtml(after)}`;
}

/** Render one key chord as a run of `kbd` elements. */
export function renderKeys(key: string): string {
  return key
    .split("+")
    .map((part) => `<kbd>${escapeHtml(KEY_LABELS[part] ?? part)}</kbd>`)
    .join("<span class=\"plus\">+</span>");
}

const KEY_LABELS: Readonly<Record<string, string>> = {
  ctrl: "Ctrl",
  alt: "Alt",
  shift: "Shift",
  up: "↑",
  down: "↓",
  left: "←",
  right: "→",
  backspace: "Backspace",
};

function keyCell(entry: CatalogEntry): string {
  if (entry.keys.length === 0) {
    return '<span class="unbound">command palette</span>';
  }
  return entry.keys.map(renderKeys).join('<span class="alt-key">or</span>');
}

function quickRow(entry: CatalogEntry): string {
  return `<tr>
      <td class="keys">${keyCell(entry)}</td>
      <td class="name">${escapeHtml(entry.title)}</td>
      <td class="summary">${escapeHtml(entry.summary)}</td>
    </tr>`;
}

function quickReference(): string {
  return GROUP_ORDER.map((group) => {
    const entries = CATALOG.filter((entry) => entry.group === group);
    if (entries.length === 0) {
      return "";
    }
    return `<section class="group" data-group="${escapeHtml(group)}">
      <h2>${escapeHtml(group)}</h2>
      ${GROUP_BLURB[group] === "" ? "" : `<p class="blurb">${escapeHtml(GROUP_BLURB[group])}</p>`}
      <table>${entries.map((entry) => quickRow(entry)).join("")}</table>
    </section>`;
  }).join("");
}

function guideCard(entry: CatalogEntry): string {
  const example = exampleFor(entry);
  const demo =
    example === undefined
      ? ""
      : `<div class="demo">
          <div class="pane"><span class="label">before</span><code>${renderSnippet(example.before)}</code></div>
          <div class="arrow" aria-hidden="true">→</div>
          <div class="pane"><span class="label">after</span><code>${renderSnippet(example.after)}</code></div>
        </div>`;

  return `<article class="card" data-search="${escapeHtml(
    `${entry.title} ${entry.summary} ${entry.detail} ${entry.keys.join(" ")}`.toLowerCase(),
  )}">
      <header>
        <h3>${escapeHtml(entry.title)}</h3>
        <div class="keys">${keyCell(entry)}</div>
      </header>
      <p class="detail">${escapeHtml(entry.detail)}</p>
      ${demo}
    </article>`;
}

function guide(): string {
  return GROUP_ORDER.map((group) => {
    const entries = CATALOG.filter((entry) => entry.group === group);
    if (entries.length === 0) {
      return "";
    }
    return `<section class="group" data-group="${escapeHtml(group)}">
      <h2>${escapeHtml(group)}</h2>
      ${GROUP_BLURB[group] === "" ? "" : `<p class="blurb">${escapeHtml(GROUP_BLURB[group])}</p>`}
      ${entries.map((entry) => guideCard(entry)).join("")}
    </section>`;
  }).join("");
}

/**
 * The whole page.
 *
 * `nonce` is required by the webview's content security policy; the caller
 * generates a fresh one per panel.
 */
export function renderCheatSheet(nonce: string): string {
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'nonce-${nonce}'; script-src 'nonce-${nonce}';">
<title>Paredit Cheat Sheet</title>
<style nonce="${nonce}">${STYLES}</style>
</head>
<body>
<header class="top">
  <div class="titles">
    <h1>Paredit for Racket</h1>
    <p class="sub">Every example below is generated by running the command, so it shows what this build actually does.</p>
  </div>
  <div class="controls">
    <div class="segmented" role="tablist">
      <button id="tab-quick" role="tab" aria-selected="true" class="active">Quick reference</button>
      <button id="tab-guide" role="tab" aria-selected="false">Guide</button>
    </div>
    <input id="filter" type="search" placeholder="Filter commands…" aria-label="Filter commands">
  </div>
</header>

<main>
  <div id="view-quick">${quickReference()}</div>
  <div id="view-guide" hidden>${guide()}</div>
  <p id="empty" hidden class="empty">No command matches that.</p>
</main>

<footer>
  <p>The bracket chords assume a US layout: <kbd>Ctrl</kbd><span class="plus">+</span><kbd>Shift</kbd><span class="plus">+</span><kbd>0</kbd> is where <code>)</code> lives there. The <kbd>Ctrl</kbd><span class="plus">+</span><kbd>←</kbd> / <kbd>→</kbd> alternates for slurp and barf are layout-independent. Rebind anything in <code>keybindings.json</code>.</p>
</footer>

<script nonce="${nonce}">${SCRIPT}</script>
</body>
</html>`;
}

